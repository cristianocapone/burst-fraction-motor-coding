# ── Burst-neuron parameters (identical to train_reacher.py) ───────────────────
DT_B=1.0; TAU_S_B=5.0; TAU_D_B=5.0
V_THRESH_B=1.0; V_RESET_B=0.0; V_RESET_BURST_B=0.9
